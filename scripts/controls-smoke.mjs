import { _electron as electron } from 'playwright'
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'
const directory = await mkdtemp(join(tmpdir(), 'bingtools-controls-'))
const endpoint = { id: randomUUID(), name: 'Status', method: 'GET', path: '/status', status: 200, enabled: true, format: 'json', body: '{"ok":true}' }
const customer = { id: randomUUID(), name: 'Controls preview', host: '127.0.0.1', port: 48765, protocol: 'http', endpoints: [endpoint] }
await writeFile(join(directory, 'simulator.json'), JSON.stringify({ schemaVersion: 5, selectedCustomerId: customer.id, customers: [customer] }))
await writeFile(join(directory, 'settings.json'), JSON.stringify({ schemaVersion: 3, language: 'en', theme: 'light', notificationPosition: 'bottom-right', sidebarWidth: 240, sidebarCollapsed: false }))
let app
const errors = []
try {
  const env = { ...process.env, BINGTOOLS_TEST_DATA: directory }; delete env.ELECTRON_RUN_AS_NODE
  app = await electron.launch({ args: [resolve('.')], env })
  const page = await app.firstWindow(); page.setDefaultTimeout(10000)
  page.on('pageerror', (error) => errors.push(error.message))
  await mkdir('test-results', { recursive: true })
  await page.getByRole('heading', { name: 'Server simulator', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => CSS.supports('appearance', 'base-select')), true)
  await page.getByRole('button', { name: 'Edit endpoint Status', exact: true }).click()
  const method = page.getByLabel('HTTP method', { exact: true })
  assert.equal(await method.evaluate((element) => getComputedStyle(element).appearance), 'base-select')
  await method.click()
  await page.getByRole('option', { name: 'POST', exact: true }).hover()
  await page.waitForTimeout(180)
  await page.screenshot({ path: 'test-results/controls-select-light.png', animations: 'disabled' })
  await page.getByRole('option', { name: 'POST', exact: true }).click()
  assert.equal(await method.inputValue(), 'POST')
  await method.focus(); await page.keyboard.press('Space'); await page.keyboard.press('Escape')
  assert.equal(await page.locator('.endpoint-dialog').isVisible(), true)
  assert.equal(await page.getByRole('dialog').count(), 1)
  await method.focus(); await page.keyboard.press('Space'); await page.keyboard.press('Home'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  assert.equal(await method.inputValue(), 'POST')
  await method.focus(); await page.keyboard.press('Space'); await page.keyboard.press('o'); await page.keyboard.press('Enter')
  assert.equal(await method.inputValue(), 'OPTIONS')
  await method.selectOption('GET')
  await page.getByRole('switch', { name: 'Delayed response', exact: true }).click()
  const delay = page.getByLabel('Response delay (ms)', { exact: true })
  await delay.fill('0')
  assert.equal(await page.getByRole('button', { name: 'Decrease Response delay (ms)', exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Increase Response delay (ms)', exact: true }).click()
  assert.equal(await delay.inputValue(), '1')
  assert.equal(await delay.evaluate((element) => document.activeElement === element), true)
  await delay.fill('60000')
  assert.equal(await page.getByRole('button', { name: 'Increase Response delay (ms)', exact: true }).isDisabled(), true)
  await page.keyboard.press('ArrowDown'); assert.equal(await delay.inputValue(), '59999')
  await delay.fill('250')
  await page.getByRole('button', { name: 'Save endpoint', exact: true }).click()
  await page.locator('.endpoint-dialog').waitFor({ state: 'hidden' })
  const result = await page.evaluate(() => window.app.simulator.getSnapshot())
  assert.equal(result.data.config.customers[0].endpoints[0].responseDelay.ms, 250)
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await page.waitForFunction(() => document.documentElement.classList.contains('dark'))
  await page.getByLabel('Notification position', { exact: true }).click()
  await page.waitForTimeout(180)
  await page.screenshot({ path: 'test-results/controls-select-dark.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByLabel('Language', { exact: true }).selectOption('zh-CN')
  await page.getByRole('link', { name: /服务器仿真/, exact: true }).click()
  await page.getByRole('button', { name: '编辑接口 Status', exact: true }).click()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(800, 560))
  await page.getByLabel('响应格式', { exact: true }).click()
  await page.waitForTimeout(180)
  await page.screenshot({ path: 'test-results/controls-narrow-dark-zh.png', animations: 'disabled' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.keyboard.press('Escape')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.getByLabel('响应格式', { exact: true }).evaluate((element) => getComputedStyle(element).transitionDuration), '0s')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '切换侧栏', exact: true }).click()
  await page.getByRole('link', { name: '运控仿真', exact: true }).click()
  await page.getByRole('button', { name: '新增客户', exact: true }).click()
  const checkbox = page.getByRole('checkbox').first()
  const before = await checkbox.isChecked(); await checkbox.focus(); await page.keyboard.press('Space')
  assert.equal(await checkbox.isChecked(), !before)
  assert.equal(await checkbox.evaluate((element) => getComputedStyle(element).appearance), 'none')
  assert.deepEqual(errors, [])
  console.log('PASS: CSS base-select supported in Electron; themed live menus, mouse selection, keyboard dismissal, numeric stepping/bounds/focus/persistence, checkbox keyboard toggle, light/dark Chinese narrow layout and reduced motion. Windows OS not exercised.')
} catch (error) { await app?.windows()[0]?.screenshot({ path: 'test-results/controls-failure.png' }).catch(() => {}); throw error }
finally { if (app) await app.close(); await rm(directory, { recursive: true, force: true }) }
